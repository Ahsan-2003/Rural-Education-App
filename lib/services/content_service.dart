      '### Formula:',
      '```',
      'a/c + b/c = (a + b)/c',
      '```',
      '',
      '### Example 1: Simple Addition',
      '```',
      '1/5 + 2/5 = (1+2)/5 = 3/5',
      '```',
      '',
      '**Think of it like this:** You have 1 piece of a 5-piece chocolate bar, then get 2 more pieces. Now you have 3/5 of the bar!',
      '',
      '### Example 2:',
      '```',
      '3/8 + 4/8 = (3+4)/8 = 7/8',
      '```',
      '',
      '### Example 3: Adding Three Fractions',
      '```',
      '2/10 + 5/10 + 1/10 = (2+5+1)/10 = 8/10 = 4/5',
      '```',
      '',
      '---',
      '',
      '## Adding Fractions with Different Denominators',
      '',
      'This requires one extra step: finding a **common denominator**.',
      '',
      '### Step-by-Step Method:',
      '',
      '**Step 1: Find the Least Common Denominator (LCD)**',
      '',
      'The LCD is the smallest number that both denominators divide into evenly.',
      '',
      '**Step 2: Convert each fraction**',
      '',
      'Multiply each fraction to make equivalent fractions with the LCD.',
      '',
      '**Step 3: Add the numerators**',
      '',
      'Keep the common denominator.',
      '',
      '**Step 4: Simplify if possible**',
      '',
      'Reduce to lowest terms.',
      '',
      '---',
      '',
      '### Example: Add 1/3 + 1/4',
      '',
      '```',
      'Step 1: Find LCD of 3 and 4',
      '→ Multiples of 3: 3, 6, 9, 12, 15...',
      '→ Multiples of 4: 4, 8, 12, 16...',
      '→ LCD = 12 ✓',
      '',
      'Step 2: Convert to equivalent fractions',
      '→ 1/3 = (1×4)/(3×4) = 4/12',
      '→ 1/4 = (1×3)/(4×3) = 3/12',
      '',
      'Step 3: Add numerators',
      '→ 4/12 + 3/12 = 7/12',
      '',
      'Step 4: Simplify',
      '→ 7/12 is already in simplest form ✓',
      '```',
      '',
      '---',
      '',
      '### Example: Add 2/3 + 3/5',
      '',
      '```',
      'LCD of 3 and 5 = 15',
      '',
      '2/3 = (2×5)/(3×5) = 10/15',
      '3/5 = (3×3)/(5×3) = 9/15',
      '',
      '10/15 + 9/15 = 19/15 = 1 4/15 (mixed number)',
      '```',
      '',
      '---',
      '',
      '## Common Mistakes to Avoid',
      '',
      '❌ **Don\'t add denominators!**',
      '```',
      '1/3 + 1/3 ≠ 2/6  ← WRONG!',
      'Correct: 1/3 + 1/3 = 2/3  ← RIGHT!',
      '```',
      '',
      '❌ **Don\'t forget to find LCD!**',
      '```',
      '1/2 + 1/3 ≠ 2/5  ← WRONG!',
      'Correct: 1/2 + 1/3 = 3/6 + 2/6 = 5/6  ← RIGHT!',
      '```',
      '',
      '✅ **Always check if you can simplify!**',
      '```',
      '2/8 + 4/8 = 6/8 = 3/4',
      '```',
      '',
      '---',
      '',
      '## Word Problems',
      '',
      '### Problem 1: School and Play',
      'Ravi spent **1/4** of his day at school and **1/3** of his day playing. What fraction of his day did he spend on both?',
      '',
      '**Solution:**',
      '```',
      '1/4 + 1/3',
      'LCD = 12',
      '1/4 = 3/12',
      '1/3 = 4/12',
      '3/12 + 4/12 = 7/12 of his day',
      '```',
      '',
      '### Problem 2: Sharing Chocolate',
      'Priya had **5/6** of a chocolate bar. Her brother gave her **1/3** more. How much does she have now?',
      '',
      '**Solution:**',
      '```',
      '5/6 + 1/3',
      'LCD = 6',
      '1/3 = 2/6',
      '5/6 + 2/6 = 7/6 = 1 1/6 chocolate bars',
      '```',
      '',
      '---',
      '',
      '## Practice Problems',
      '',
      'Try these on your own:',
      '',
      '1. 3/10 + 4/10 = ?',
      '2. 1/2 + 1/5 = ?',
      '3. 2/3 + 1/6 = ?',
      '4. 3/4 + 1/8 = ?',
      '5. 2/5 + 3/10 = ?',
      '',
      '---',
      '',
      '**Excellent!** You can now add fractions with confidence!',
      'Take the quiz to practice more.',
    ].join('\n');

    return Lesson(
      id: 'lesson_2',
      title: 'Adding Fractions',
      content: content,
