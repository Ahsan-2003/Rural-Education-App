import '../models/lesson.dart';

class ContentService {
  // Singleton pattern
  ContentService._();
  static final ContentService _instance = ContentService._();
  factory ContentService() => _instance;

  // Cache lessons in memory
  List<Lesson>? _cachedLessons;

  // Get all lessons
  List<Lesson> getLessons() {
    if (_cachedLessons != null) {
      return _cachedLessons!;
    }
    _cachedLessons = _createSampleLessons();
    return _cachedLessons!;
  }

  // Get a specific lesson by ID
  Lesson? getLessonById(String id) {
    try {
      return getLessons().firstWhere((l) => l.id == id);
    } catch (e) {
      return null;
    }
  }

  // Get lessons count
  int getLessonCount() {
    return getLessons().length;
  }

  // Create sample lessons
  List<Lesson> _createSampleLessons() {
    return [_createLesson1(), _createLesson2(), _createLesson3()];
  }

